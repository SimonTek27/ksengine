// Feature Generation
// ============================================================================

QString GCodeGenerator::generatePerimeters(const Polygons2D& perimeters, const SliceSettings& settings, bool outerWall) {
    QString out;

    double speed = outerWall ? settings.outerWallSpeed : settings.innerWallSpeed;
    setFeedrate(out, speed * 60);

    for (const auto& poly : perimeters) {
        if (poly.vertices.size() < 3) continue;

        // Move to start
        const auto& start = poly.vertices.front();
        travelTo(out, start.x, start.y, m_currentZ);

        // Prime if needed
        if (settings.retractionEnabled && m_currentE > 0) {
            out += generatePrime(settings);
        }

        // Trace perimeter
        for (size_t i = 0; i < poly.vertices.size(); ++i) {
            const auto& v = poly.vertices[i];
            double extrusion = calculateExtrusion(
                (i > 0) ? std::sqrt(std::pow(v.x - poly.vertices[i-1].x, 2) + std::pow(v.y - poly.vertices[i-1].y, 2)) : 0,
                settings.lineWidth, settings.layerHeight, settings.filamentDiameter
            );
            moveTo(out, v.x, v.y, m_currentZ, speed * 60, extrusion);
        }

        // Close loop
        const auto& end = poly.vertices.front();
        double extrusion = std::sqrt(std::pow(end.x - poly.vertices.back().x, 2) + std::pow(end.y - poly.vertices.back().y, 2));
        extrusion = calculateExtrusion(extrusion, settings.lineWidth, settings.layerHeight, settings.filamentDiameter);
        moveTo(out, end.x, end.y, m_currentZ, speed * 60, extrusion);
    }

    return out;
}

QString GCodeGenerator::generateInfill(const Polygons2D& infill, const SliceSettings& settings) {
    QString out;
    setFeedrate(out, settings.infillSpeed * 60);

    for (const auto& poly : infill) {
        if (poly.vertices.size() < 2) continue;

        // Infill is typically lines, not closed loops
        travelTo(out, poly.vertices[0].x, poly.vertices[0].y, m_currentZ);

        for (size_t i = 1; i < poly.vertices.size(); ++i) {
            const auto& v = poly.vertices[i];
            const auto& prev = poly.vertices[i-1];
            double dist = std::sqrt(std::pow(v.x - prev.x, 2) + std::pow(v.y - prev.y, 2));
            double extrusion = calculateExtrusion(dist, settings.infillLineWidth > 0 ? settings.infillLineWidth : settings.lineWidth,
                                                  settings.layerHeight, settings.filamentDiameter);
            moveTo(out, v.x, v.y, m_currentZ, settings.infillSpeed * 60, extrusion);
        }
    }

    return out;
}

QString GCodeGenerator::generateSupport(const Polygons2D& support, const SliceSettings& settings) {
    QString out;
    setFeedrate(out, settings.supportSpeed * 60);

    for (const auto& poly : support) {
        if (poly.vertices.size() < 2) continue;

        travelTo(out, poly.vertices[0].x, poly.vertices[0].y, m_currentZ);

        for (size_t i = 1; i < poly.vertices.size(); ++i) {
            const auto& v = poly.vertices[i];
            const auto& prev = poly.vertices[i-1];
            double dist = std::sqrt(std::pow(v.x - prev.x, 2) + std::pow(v.y - prev.y, 2));
            double extrusion = calculateExtrusion(dist, settings.lineWidth, settings.layerHeight, settings.filamentDiameter);
            moveTo(out, v.x, v.y, m_currentZ, settings.supportSpeed * 60, extrusion);
        }
    }

    return out;
}

QString GCodeGenerator::generateBrim(const Polygons2D& brim, const SliceSettings& settings) {
    QString out;
    setFeedrate(out, settings.initialLayerSpeed * 60);

    for (const auto& poly : brim) {
        if (poly.vertices.size() < 3) continue;

        travelTo(out, poly.vertices[0].x, poly.vertices[0].y, m_currentZ);

        for (size_t i = 1; i < poly.vertices.size(); ++i) {
            const auto& v = poly.vertices[i];
            const auto& prev = poly.vertices[i-1];
            double dist = std::sqrt(std::pow(v.x - prev.x, 2) + std::pow(v.y - prev.y, 2));
            double extrusion = calculateExtrusion(dist, settings.lineWidth, settings.initialLayerHeight > 0 ? settings.initialLayerHeight : settings.layerHeight,
                                                  settings.filamentDiameter);
            moveTo(out, v.x, v.y, m_currentZ, settings.initialLayerSpeed * 60, extrusion);
        }
        // Close
        const auto& start = poly.vertices.front();
        const auto& end = poly.vertices.back();
        double dist = std::sqrt(std::pow(start.x - end.x, 2) + std::pow(start.y - end.y, 2));
        double extrusion = calculateExtrusion(dist, settings.lineWidth, settings.initialLayerHeight > 0 ? settings.initialLayerHeight : settings.layerHeight,
                                              settings.filamentDiameter);
        moveTo(out, start.x, start.y, m_currentZ, settings.initialLayerSpeed * 60, extrusion);
    }

    return out;
}

QString GCodeGenerator::generateSkirt(const Polygons2D& skirt, const SliceSettings& settings) {
    return generateBrim(skirt, settings); // Similar generation
}

// ============================================================================
// Movement & Extrusion
// ============================================================================

QString GCodeGenerator::generateTravel(const Vector3& from, const Vector3& to, const SliceSettings& settings) {
    QString out;

    // Retract before travel if enabled and distance > min
    double dist = std::sqrt(std::pow(to.x - from.x, 2) + std::pow(to.y - from.y, 2));
    if (settings.retractionEnabled && dist > settings.minTravelForRetract) {
        out += generateRetract(settings);
    }

    // Z-hop if enabled
    if (settings.zHopEnabled && settings.zHopHeight > 0) {
        double hopZ = from.z + settings.zHopHeight;
        setFeedrate(out, settings.zHopSpeed > 0 ? settings.zHopSpeed * 60 : settings.travelSpeed * 60);
        moveTo(out, from.x, from.y, hopZ, settings.travelSpeed * 60, 0);
    }

    // Travel move
    setFeedrate(out, settings.travelSpeed * 60);
    moveTo(out, to.x, to.y, to.z, settings.travelSpeed * 60, 0);

    // Z-hop down
    if (settings.zHopEnabled && settings.zHopHeight > 0) {
        setFeedrate(out, settings.zHopSpeed > 0 ? settings.zHopSpeed * 60 : settings.travelSpeed * 60);
        moveTo(out, to.x, to.y, to.z, settings.travelSpeed * 60, 0);
    }

    // Prime after travel
    if (settings.retractionEnabled && dist > settings.minTravelForRetract) {
        out += generatePrime(settings);
    }

    return out;
}

QString GCodeGenerator::generateRetract(const SliceSettings& settings) {
    QString out;
    if (settings.retractDistance > 0) {
        double e = m_relativeExtrusion ? -settings.retractDistance : m_currentE - settings.retractDistance;
        writeLine(out, QString("G1 E%1 F%2 ; Retract").arg(Impl::fmtE(e)).arg(settings.retractSpeed * 60));
        if (m_relativeExtrusion) {
            m_currentE -= settings.retractDistance;
        } else {
            m_currentE = e;
        }
    }
    return out;
}

QString GCodeGenerator::generatePrime(const SliceSettings& settings) {
    QString out;
    double primeDist = settings.primeDistance > 0 ? settings.primeDistance : settings.retractDistance;
    double e = m_relativeExtrusion ? primeDist : m_currentE + primeDist;
    writeLine(out, QString("G1 E%1 F%2 ; Prime").arg(Impl::fmtE(e)).arg(settings.retractSpeed * 60));
    if (m_relativeExtrusion) {
        m_currentE += primeDist;
    } else {
        m_currentE = e;
    }
    return out;
}

QString GCodeGenerator::generateZHop(double z, const SliceSettings& settings) {
    QString out;
    setFeedrate(out, settings.zHopSpeed > 0 ? settings.zHopSpeed * 60 : settings.travelSpeed * 60);
    moveTo(out, m_currentX, m_currentY, z, settings.zHopSpeed > 0 ? settings.zHopSpeed * 60 : settings.travelSpeed * 60, 0);
    return out;
}

// ============================================================================
// Temperature & Fan
