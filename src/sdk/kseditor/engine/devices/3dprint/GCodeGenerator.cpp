QString GCodeGenerator::generateHeader(const PrinterProfile& printer, const SliceSettings& settings, const BoundingBox& bounds) {
    QString out;
    writeComment(out, "Generated by ksEditor 3D Printing Module");
    writeComment(out, QString("Printer: %1 (%2)").arg(printer.name).arg(printer.id));
    writeComment(out, QString("Slicing profile: %1").arg(settings.outputFilename.isEmpty() ? "default" : settings.outputFilename));
    writeComment(out, QString("Layers: %1").arg(m_totalLayers));
    writeComment(out, QString("Bounds: X%.1f Y%.1f Z%.1f").arg(bounds.size().x).arg(bounds.size().y).arg(bounds.size().z));
    writeComment(out, QString("Estimated time: %1s").arg(m_totalTime));
    writeComment(out, QString("Estimated filament: %1mm").arg(m_totalFilament));
    writeComment(out, "");

    // Flavor-specific headers
    switch (printer.gcodeFlavor) {
        case GCodeFlavor::Marlin:
        case GCodeFlavor::Prusa:
        case GCodeFlavor::Bambu:
            writeLine(out, "G21 ; Units: millimeters");
            writeLine(out, "G90 ; Absolute positioning");
            writeLine(out, "M82 ; Absolute extrusion");
            break;
        case GCodeFlavor::Klipper:
            writeLine(out, "G21");
            writeLine(out, "G90");
            writeLine(out, "M83 ; Relative extrusion for Klipper");
            m_relativeExtrusion = true;
            break;
        case GCodeFlavor::RepRap:
            writeLine(out, "G21");
            writeLine(out, "G90");
            writeLine(out, "M83");
            m_relativeExtrusion = true;
            break;
        default:
            writeLine(out, "G21");
            writeLine(out, "G90");
            writeLine(out, "M82");
            break;
    }

    return out;
}

QString GCodeGenerator::generateFooter(const PrinterProfile& printer, const SliceSettings& settings) {
    QString out;
    writeComment(out, "");
    writeComment(out, "Print complete");
    writeComment(out, QString("Total filament used: %1mm").arg(m_totalFilament, 0, 'f', 2));
    writeComment(out, QString("Estimated print time: %1s").arg(m_totalTime, 0, 'f', 0));
    return out;
}

// ============================================================================
// Startup / Shutdown
// ============================================================================

QString GCodeGenerator::generateStartup(const PrinterProfile& printer, const SliceSettings& settings) {
    QString out;
    writeComment(out, "=== STARTUP ===");

    QString startup = printer.startGcode.isEmpty() ? defaultStartupGcode(printer, settings) : printer.startGcode;

    // Replace placeholders
    startup.replace("{nozzle_temp}", QString::number(settings.nozzleTemp, 'f', 0));
    startup.replace("{bed_temp}", QString::number(settings.bedTemp, 'f', 0));
    startup.replace("{travel_speed}", QString::number(settings.travelSpeed * 60, 'f', 0)); // mm/min
    startup.replace("{print_speed}", QString::number(settings.printSpeed * 60, 'f', 0));
    startup.replace("{bed_max_y}", QString::number(printer.buildVolumeY, 'f', 1));
    startup.replace("{bed_max_x}", QString::number(printer.buildVolumeX, 'f', 1));

    // Also replace with _ variants
    startup.replace("{nozzle_temperature}", QString::number(settings.nozzleTemp, 'f', 0));
    startup.replace("{bed_temperature}", QString::number(settings.bedTemp, 'f', 0));
    startup.replace("{initial_layer_height}", QString::number(settings.initialLayerHeight > 0 ? settings.initialLayerHeight : settings.layerHeight, 'f', 2));

    out += startup + "\n";

    // Set initial temperatures if not in startup
    if (!startup.contains("M104") && !startup.contains("M109")) {
        out += generateSetHotendTemp(settings.nozzleTemp, true, printer);
    }
    if (!startup.contains("M140") && !startup.contains("M190")) {
        out += generateSetBedTemp(settings.bedTemp, true, printer);
    }

    return out;
}

QString GCodeGenerator::generateShutdown(const PrinterProfile& printer, const SliceSettings& settings) {
    QString out;
    writeComment(out, "=== SHUTDOWN ===");

    QString shutdown = printer.endGcode.isEmpty() ? defaultShutdownGcode(printer, settings) : printer.endGcode;

    shutdown.replace("{bed_max_y}", QString::number(printer.buildVolumeY, 'f', 1));
    shutdown.replace("{bed_max_x}", QString::number(printer.buildVolumeX, 'f', 1));

    out += shutdown + "\n";
    return out;
}

QString GCodeGenerator::defaultStartupGcode(const PrinterProfile& printer, const SliceSettings& settings) {
    return QString(R"(
; Default startup
G21
G90
M82
M104 S%1
M140 S%2
G28
G1 Z5 F5000
M190 S%2
M109 S%1
G92 E0
G1 X10 Y10 Z0.2 F3000
G1 X100 E15 F1000
G92 E0
)").arg(settings.nozzleTemp).arg(settings.bedTemp);
}

QString GCodeGenerator::defaultShutdownGcode(const PrinterProfile& printer, const SliceSettings& settings) {
    return QString(R"(
; Default shutdown
M104 S0
M140 S0
G91
G1 E-2 F2700
G1 Z5 F1000
G90
G1 X0 Y%1 F5000
M84
)").arg(printer.buildVolumeY);
}

