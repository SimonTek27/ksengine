void GCodeGenerator::resetState() {
    m_currentX = m_currentY = m_currentZ = 0;
    m_currentE = 0;
    m_currentFeedrate = 0;
    m_relativeExtrusion = false;
    m_relativePositioning = false;
    m_currentLayer = 0;
    m_totalLayers = 0;
    m_totalFilament = 0;
    m_totalTime = 0;
}

void GCodeGenerator::writeLine(QString& output, const QString& line) {
    output += line + "\n";
}

void GCodeGenerator::writeComment(QString& output, const QString& comment) {
    if (comment.isEmpty()) {
        output += "\n";
    } else {
        output += "; " + comment + "\n";
    }
}

void GCodeGenerator::moveTo(QString& output, double x, double y, double z, double feedrate, double extrusion) {
    QString line = "G1";
    if (std::abs(x - m_currentX) > 0.001) line += " X" + Impl::fmt(x);
    if (std::abs(y - m_currentY) > 0.001) line += " Y" + Impl::fmt(y);
    if (std::abs(z - m_currentZ) > 0.001) line += " Z" + Impl::fmt(z);
    if (extrusion != 0) line += " E" + Impl::fmtE(extrusion);
    if (feedrate > 0 && std::abs(feedrate - m_currentFeedrate) > 1) {
        line += " F" + Impl::fmt(feedrate, 0);
        m_currentFeedrate = feedrate;
    }
    writeLine(output, line);

    m_currentX = x;
    m_currentY = y;
    m_currentZ = z;
    if (extrusion != 0) {
        if (m_relativeExtrusion) {
            m_currentE += extrusion;
        } else {
            m_currentE = extrusion;
        }
        m_totalFilament += std::abs(extrusion);
    }
}

void GCodeGenerator::travelTo(QString& output, double x, double y, double z) {
    moveTo(output, x, y, z, m_currentFeedrate > 0 ? m_currentFeedrate : 9000, 0);
}

void GCodeGenerator::setFeedrate(QString& output, double feedrate) {
    if (std::abs(feedrate - m_currentFeedrate) > 1) {
        writeLine(output, QString("G1 F%1").arg(Impl::fmt(feedrate, 0)));
        m_currentFeedrate = feedrate;
    }
}

void GCodeGenerator::setExtrusionMode(QString& output, bool relative) {
    if (relative != m_relativeExtrusion) {
        writeLine(output, relative ? "M83 ; Relative extrusion" : "M82 ; Absolute extrusion");
        m_relativeExtrusion = relative;
    }
}

void GCodeGenerator::setPositioningMode(QString& output, bool relative) {
    if (relative != m_relativePositioning) {
        writeLine(output, relative ? "G91 ; Relative positioning" : "G90 ; Absolute positioning");
        m_relativePositioning = relative;
    }
}

void GCodeGenerator::setFanSpeed(QString& output, int speed) {
    writeLine(output, QString("M106 S%1").arg(std::clamp(speed, 0, 255)));
}

QString GCodeGenerator::formatCoordinate(double value, int precision) const {
    return QString::number(value, 'f', precision);
}

QString GCodeGenerator::formatExtrusion(double value, int precision) const {
    return QString::number(value, 'f', precision);
}

double GCodeGenerator::calculateExtrusion(double distance, double lineWidth, double layerHeight, double filamentDiameter) const {
    if (distance <= 0) return 0;
    double crossSection = lineWidth * layerHeight;
    double filamentArea = M_PI * filamentDiameter * filamentDiameter / 4.0;
    return distance * crossSection / filamentArea;
}

