QString GCodeGenerator::generateSetHotendTemp(double temp, bool wait, const PrinterProfile& printer) {
    QString out;
    if (wait) {
        writeLine(out, QString("M109 S%1 ; Wait for hotend").arg(static_cast<int>(temp)));
    } else {
        writeLine(out, QString("M104 S%1 ; Set hotend temp").arg(static_cast<int>(temp)));
    }
    return out;
}

QString GCodeGenerator::generateSetBedTemp(double temp, bool wait, const PrinterProfile& printer) {
    QString out;
    if (wait) {
        writeLine(out, QString("M190 S%1 ; Wait for bed").arg(static_cast<int>(temp)));
    } else {
        writeLine(out, QString("M140 S%1 ; Set bed temp").arg(static_cast<int>(temp)));
    }
    return out;
}

QString GCodeGenerator::generateFanSpeed(int speed, const SliceSettings& settings) {
    QString out;
    speed = std::clamp(speed, 0, 255);
    writeLine(out, QString("M106 S%1 ; Fan speed %2%").arg(speed).arg(speed * 100 / 255));
    return out;
}

