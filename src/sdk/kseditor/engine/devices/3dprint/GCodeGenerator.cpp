// Layer Generation
// ============================================================================

QString GCodeGenerator::generateLayer(const LayerSlice& layer, int layerIndex, int totalLayers,
                                      const PrinterProfile& printer, const SliceSettings& settings) {
    QString out;

    if (layer.isFirstLayer) {
        writeComment(out, QString("=== LAYER %1 (FIRST LAYER) ===").arg(layerIndex + 1));
        // First layer specific settings
        setFeedrate(out, settings.initialLayerSpeed * 60);
    } else if (layer.isLastLayer) {
        writeComment(out, QString("=== LAYER %1 (LAST LAYER) ===").arg(layerIndex + 1));
    } else {
        writeComment(out, QString("=== LAYER %1 ===").arg(layerIndex + 1));
    }

    writeComment(out, QString("Z = %1").arg(Impl::fmt(layer.z, 3)));

    // Set layer Z
    moveTo(out, m_currentX, m_currentY, layer.z, settings.travelSpeed * 60);

    // Fan control
    if (settings.enableCooling) {
        int fanSpeed = layerIndex < settings.fanStartLayer ? settings.initialFanSpeed : settings.fanSpeed;
        out += generateFanSpeed(fanSpeed, settings);
    }

    // Process perimeters first (outer wall, then inner walls)
    if (!layer.perimeters.empty()) {
        writeComment(out, "--- Perimeters ---");
        out += generatePerimeters(layer.perimeters, settings, true); // outer wall first

        // Inner walls
        if (settings.wallCount > 1) {
            setFeedrate(out, settings.innerWallSpeed * 60);
            out += generatePerimeters(layer.perimeters, settings, false);
        }
    }

    // Infill
    if (!layer.infill.empty()) {
        writeComment(out, "--- Infill ---");
        setFeedrate(out, settings.infillSpeed * 60);
        out += generateInfill(layer.infill, settings);
    }

    // Support
    if (!layer.support.empty()) {
        writeComment(out, "--- Support ---");
        setFeedrate(out, settings.supportSpeed * 60);
        out += generateSupport(layer.support, settings);
    }

    // Brim/Skirt (first layer only)
    if (layer.isFirstLayer) {
        if (!layer.brim.empty()) {
            writeComment(out, "--- Brim/Skirt ---");
            setFeedrate(out, settings.initialLayerSpeed * 60);
            out += generateBrim(layer.brim, settings);
        }
    }

    return out;
}

QString GCodeGenerator::generateLayerChange(int layerIndex, const PrinterProfile& printer, const SliceSettings& settings) {
    QString out;
    if (!printer.layerChangeGcode.isEmpty()) {
        QString lc = printer.layerChangeGcode;
        lc.replace("{layer_num}", QString::number(layerIndex + 1));
        lc.replace("{layer_z}", Impl::fmt(settings.layerHeight * (layerIndex + 1), 3));
        out += lc + "\n";
    }
    return out;
}

