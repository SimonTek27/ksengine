struct GCodeGenerator::Impl {
    // Helper to format numbers for G-code
    static QString fmt(double v, int prec = 3) {
        return QString::number(v, 'f', prec);
    }
    static QString fmtE(double v, int prec = 5) {
        return QString::number(v, 'f', prec);
    }
};

GCodeGenerator::GCodeGenerator(QObject* parent) : QObject(parent), d(std::make_unique<Impl>()) {}
GCodeGenerator::~GCodeGenerator() = default;

// ============================================================================
// Main Generation
// ============================================================================

QString GCodeGenerator::generateGCode(const SliceInfo& sliceInfo, const PrinterProfile& printer, const SliceSettings& settings) {
    return generateFromLayers(sliceInfo.slices, printer, settings, sliceInfo.boundingBox);
}

QString GCodeGenerator::generateFromLayers(const LayerSlices& slices, const PrinterProfile& printer, const SliceSettings& settings,
                                            const BoundingBox& bounds) {
    QString gcode;
    resetState();
    m_totalLayers = slices.size();

    // Header
    gcode += generateHeader(printer, settings, bounds);
    gcode += "\n";

    // Startup
    gcode += generateStartup(printer, settings);
    gcode += "\n";

    // Layers
    for (size_t i = 0; i < slices.size(); ++i) {
        m_currentLayer = static_cast<int>(i);
        if (i > 0) {
            gcode += generateLayerChange(m_currentLayer, printer, settings);
        }
        gcode += generateLayer(slices[i], m_currentLayer, m_totalLayers, printer, settings);

        // Progress
        if (m_currentLayer % 10 == 0) {
            emit generationProgress(static_cast<int>((m_currentLayer + 1) * 100 / m_totalLayers),
                                   QString("Generating layer %1/%2").arg(m_currentLayer + 1).arg(m_totalLayers));
        }
    }

    // Shutdown
    gcode += generateShutdown(printer, settings);
    gcode += "\n";

    // Footer
    gcode += generateFooter(printer, settings);

    emit generationComplete(gcode);
    return gcode;
}

void GCodeGenerator::generateAsync(const SliceInfo& sliceInfo, const PrinterProfile& printer, const SliceSettings& settings,
                                   ProgressCallback progress, std::function<void(const QString& gcode)> complete) {
    QtConcurrent::run([this, sliceInfo, &printer, settings, progress, complete]() {
        QString gcode = generateFromLayers(sliceInfo.slices, printer, settings, sliceInfo.boundingBox);
        if (complete) complete(gcode);
    });
}

